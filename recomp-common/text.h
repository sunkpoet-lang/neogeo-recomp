// (ForkAde's fork) The Spanish letters and signs, for the in-game chat: a column per 16 bits, bit 0 two rows above
// the cell (a capital's accent), bit 2 its top row; any other character outside ASCII is drawn as "?"
struct ExtraGlyph {
    uint32_t code;
    uint16_t columns[5];
};
