"""Decode pinned original PNGs without artwork edits; embed exact RGBA using zlib."""
from pathlib import Path
import zlib,json,hashlib
from PIL import Image
root=Path(__file__).resolve().parents[1];assets=root/'assets/input-display'
names=['a','b','c','d']+[str(i) for i in range(1,10)]
payload=bytearray();entries=[]
for name in names:
    path=assets/('neogeo' if name in 'abcd' else 'stick')/(name+'.png')
    with Image.open(path) as image:
        rgba=image.convert('RGBA');raw=rgba.tobytes();packed=zlib.compress(raw,9)
        entries.append((rgba.width,rgba.height,len(payload),len(packed)))
        assert zlib.decompress(packed)==raw
        payload.extend(packed)
text='// Generated by tools/embed_input_art.py from unmodified InputDisplay PNGs.\n// GPL-3.0: see assets/input-display/README.md and LICENSE.\n#pragma once\n#include <cstdint>\nnamespace port::input_art {\nstruct Entry {int width,height,offset,bytes;};\ninline constexpr Entry entries[]={\n'
text+=''.join('    {%d,%d,%d,%d},\n'%row for row in entries)+'};\ninline constexpr uint8_t packed[]={\n'
text+=''.join('    '+','.join('0x%02x'%b for b in payload[i:i+24])+',\n' for i in range(0,len(payload),24))+'};\n}\n'
(root/'port/input_art_data.h').write_bytes(text.encode())
print('Embedded',len(entries),'unchanged RGBA images;',len(payload),'compressed bytes')
