"""Compile the presenter (port/present.cpp)'s shaders (port/shaders/*.vert, *.frag; Vulkan GLSL 450 with SDL_GPU's resource
layout: vertex uniforms in set 1, fragment samplers in set 2, fragment uniforms in set 3) to SPIR-V with
glslangValidator and to Metal Shading Language with spirv-cross, and write port/shaders.inc. That file is
committed, so building the port needs neither tool.

  python3 tools/gen_shaders.py
"""
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCES = ROOT / "port" / "shaders"
OUTPUT = ROOT / "port" / "shaders.inc"


def compile_stage(path, tmp):
    stage = path.suffix[1:]
    spv = Path(tmp) / (path.name + ".spv")
    r = subprocess.run(["glslangValidator", "-V", "-S", stage, "-o", str(spv), str(path)], capture_output=True, text=True)
    if r.returncode != 0:
        sys.exit(f"{path.name}: glslang failed:\n{r.stdout}{r.stderr}")
    msl = subprocess.run(["spirv-cross", "--msl", "--msl-version", "20100", "--msl-decoration-binding", str(spv)],
                         capture_output=True, text=True)
    if msl.returncode != 0:
        sys.exit(f"{path.name}: spirv-cross failed:\n{msl.stderr}")
    return spv.read_bytes(), msl.stdout


def main():
    out = ["// SPDX-License-Identifier: GPL-3.0-only",
           "// Copyright (C) 2026 Tommy McLeroy. Part of cps2recomp.",
           "// Generated by tools/gen_shaders.py from port/shaders/. Do not edit.", ""]
    with tempfile.TemporaryDirectory() as tmp:
        for path in sorted(SOURCES.iterdir()):
            if path.suffix not in (".vert", ".frag"):
                continue
            name = path.stem + "_" + path.suffix[1:]
            spv, msl = compile_stage(path, tmp)
            data = ", ".join(f"0x{b:02x}" for b in spv)
            out.append(f"constexpr unsigned char k_{name}_spirv[] = {{{data}}};")
            lines = msl.replace("\\", "\\\\").replace('"', '\\"').split("\n")
            out.append(f"constexpr const char k_{name}_msl[] =")
            out.extend(f'    "{line}\\n"' for line in lines)
            out[-1] += ";"
            out.append("")
    OUTPUT.write_text("\n".join(out))
    print(f"wrote {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
